// LVGL 9.6 configuration for rez-pad. Only settings that differ from LVGL's defaults
// (lv_conf_internal.h) are listed. Found through LV_CONF_INCLUDE_SIMPLE (platformio.ini).
#ifndef LV_CONF_H
#define LV_CONF_H

// ---- Color and memory ----
// RGB565; LovyanGFX converts to the panel's RGB666. (LVGL 9.6 replaced LV_COLOR_DEPTH with this.)
#define LV_COLOR_FORMAT_DEFAULT LV_COLOR_FORMAT_RGB565

// LVGL objects in PSRAM: plain malloc kept every small block in internal RAM (96 widgets left 3 KB).
#define LV_USE_STDLIB_MALLOC LV_STDLIB_CUSTOM  // PSRAM, see src/ui/lv_mem_psram.c
#define LV_USE_STDLIB_STRING LV_STDLIB_CLIB
#define LV_USE_STDLIB_SPRINTF LV_STDLIB_CLIB

// ---- Rendering ----
// 30 FPS cap. Partial updates stay small; the SPI link (about 93 ms per full frame) is the real
// limit for big redraws. Marquee speed (widgets/common.h) is matched to 1 px per frame.
#define LV_DEF_REFR_PERIOD 33
#define LV_DPI_DEF 165         // 3.5" 480x320
#define LV_USE_OS LV_OS_NONE   // LVGL is only touched from the UI loop

// ---- Logging and debugging ----
#define LV_USE_LOG 1
#define LV_LOG_LEVEL LV_LOG_LEVEL_WARN
#define LV_LOG_PRINTF 0  // routed to Serial with lv_log_register_print_cb()
#define LV_USE_SYSMON 1
#define LV_USE_PERF_MONITOR 1  // shown on demand with the `perf` console command
#define LV_USE_MEM_MONITOR 0

// ---- Fonts ----
// Generated by tools/gen_fonts.py: Latin, Latin Extended-A, Cyrillic, Greek and LV_SYMBOL_*.
#define LV_FONT_MONTSERRAT_14 0
#define LV_FONT_CUSTOM_DECLARE \
  LV_FONT_DECLARE(rp_font_14) LV_FONT_DECLARE(rp_font_20) LV_FONT_DECLARE(rp_font_28) LV_FONT_DECLARE(rp_font_48)
#define LV_FONT_DEFAULT &rp_font_20
#define LV_USE_FONT_PLACEHOLDER 1  // missing glyphs (CJK) draw as a box instead of nothing

// ---- Features not needed ----
#define LV_USE_THEME_SIMPLE 0
#define LV_USE_THEME_MONO 0
#define LV_BUILD_EXAMPLES 0
#define LV_BUILD_DEMOS 0

#endif  // LV_CONF_H
