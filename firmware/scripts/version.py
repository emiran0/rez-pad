# PlatformIO pre-build script: the firmware version from the repo's VERSION file (one version for
# host, firmware and installer, see docs/versioning.md), plus the git commit. Writes
# src/version_info.cpp (not in git) only when it changes, so a new commit recompiles one file.
import os
import subprocess

Import("env")  # noqa: F821 (provided by PlatformIO)

project = env.subst("$PROJECT_DIR")  # noqa: F821
root = os.path.dirname(project)
with open(os.path.join(root, "VERSION"), encoding="utf-8") as f:
    version = f.read().strip()


def git(*args):
    try:
        return subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


commit = git("rev-parse", "--short=7", "HEAD")
dirty = bool(git("status", "--porcelain", "--untracked-files=no"))
full = version + (f"+{commit}" if commit else "") + (".dirty" if dirty else "")

parts = [int(p) if p.isdigit() else 0 for p in (version.split("-")[0].split(".") + ["0", "0"])[:3]]
# USB bcdDevice 0xJJMN: major in the high byte, minor and patch one hex digit each.
bcd = (min(parts[0], 99) // 10 << 12) | (min(parts[0], 99) % 10 << 8) | (min(parts[1], 9) << 4) | min(parts[2], 9)

source = f'''// Generated by scripts/version.py from VERSION and git. Do not edit; not in git.
#include "version_info.h"

namespace rp {{
// The tag lets the host read the version out of a firmware image (web firmware update).
extern const char kFwVersionTag[];
__attribute__((used)) const char kFwVersionTag[] = "rez-pad-fw-version:{full}";
const char* const kFwVersion = kFwVersionTag + 19;
const uint16_t kFwVersionBcd = 0x{bcd:04X};
}}  // namespace rp
'''
path = os.path.join(project, "src", "version_info.cpp")
old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
if old != source:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(source)
print(f"rez-pad firmware {full}")
