"""Generate the firmware's C headers from the shared config files in docs/.

- docs/default-config.json -> firmware/lib/config_logic/src/default_config.h (built-in default
  config, compact JSON). The host embeds the same JSON file, so both start from the same default.
- docs/config-test-vectors.json -> firmware/test/test_config/vectors.h (validation cases shared
  with the host tests).

Usage: python tools/gen_config_headers.py
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent


def c_string(text: str) -> str:
    """UTF-8 C string literal split into lines. Octal escapes for non-ASCII (no hex run-on)."""
    out = []
    line = ''
    for b in text.encode('utf-8'):
        c = chr(b)
        if c == '"':
            s = '\\"'
        elif c == '\\':
            s = '\\\\'
        elif 32 <= b < 127:
            s = c
        else:
            s = '\\%03o' % b
        line += s
        if len(line) >= 100:
            out.append('    "' + line + '"')
            line = ''
    if line:
        out.append('    "' + line + '"')
    return '\n'.join(out)


def write(path: pathlib.Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding='utf-8', newline='\n')
    print(f'wrote {path.relative_to(ROOT)}')


def main() -> None:
    default = json.loads((ROOT / 'docs' / 'default-config.json').read_text(encoding='utf-8'))
    compact = json.dumps(default, ensure_ascii=False, separators=(',', ':'))
    write(ROOT / 'firmware' / 'lib' / 'config_logic' / 'src' / 'default_config.h',
          '// Generated by tools/gen_config_headers.py from docs/default-config.json. Do not edit.\n'
          '#pragma once\n\n'
          'namespace rp {\nnamespace cfg {\n\n'
          'static const char kDefaultConfigJson[] =\n' + c_string(compact) + ';\n\n'
          '}  // namespace cfg\n}  // namespace rp\n')

    vectors = json.loads((ROOT / 'docs' / 'config-test-vectors.json').read_text(encoding='utf-8'))
    write(ROOT / 'firmware' / 'test' / 'test_config' / 'vectors.h',
          '// Generated by tools/gen_config_headers.py from docs/config-test-vectors.json. Do not edit.\n'
          '#pragma once\n\n'
          'static const char kConfigVectorsJson[] =\n' +
          c_string(json.dumps(vectors, ensure_ascii=False, separators=(',', ':'))) + ';\n')


if __name__ == '__main__':
    main()
